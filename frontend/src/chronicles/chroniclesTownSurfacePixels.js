// Deterministic, self-contained surface detail for Swordhaven facades and roads.
// Keep the classic pixel atlas for the overworld; these close-up town surfaces
// need finer mortar, weathering and grain. Shared DataTextures: no downloads.
export const CHRONICLES_TOWN_SURFACE_KINDS = Object.freeze(['stucco', 'masonry', 'brick', 'roof', 'timber', 'cobble']);

const SURFACES = Object.freeze({
  stucco: { size: 128, base: [240, 231, 215] },
  masonry: { size: 256, base: [221, 215, 204], width: 64, height: 32 },
  // Long, shallow fired-clay courses: four bricks across and sixteen rows
  // repeat seamlessly, including the half-brick bond on alternate courses.
  brick: { size: 256, base: [226, 172, 148], width: 64, height: 16 },
  roof: { size: 128, base: [205, 195, 184], width: 32, height: 16 },
  timber: { size: 128, base: [206, 179, 151] },
  cobble: { size: 256, base: [217, 211, 197], width: 32, height: 16 },
});

function hash(x, y, salt = 0) {
  let h = Math.imul(x + 374761393 + salt * 668265263, 0x27d4eb2d)
    ^ Math.imul(y + 668265263, 0x165667b1);
  h ^= h >>> 15;
  h = Math.imul(h, 0x85ebca6b);
  return ((h ^ (h >>> 13)) >>> 0) / 4294967295;
}

function noise(x, y, size, cells, salt) {
  const u = x * cells / size;
  const v = y * cells / size;
  const ix = Math.floor(u);
  const iy = Math.floor(v);
  const fx = (u - ix) ** 2 * (3 - 2 * (u - ix));
  const fy = (v - iy) ** 2 * (3 - 2 * (v - iy));
  const h = (dx, dy) => hash((ix + dx) % cells, (iy + dy) % cells, salt);
  return (h(0, 0) * (1 - fx) + h(1, 0) * fx) * (1 - fy)
    + (h(0, 1) * (1 - fx) + h(1, 1) * fx) * fy;
}

function surfaceDetail(kind, x, y, spec) {
  const { size } = spec;
  const grain = hash(x, y, 13) - 0.5;
  const erosion = noise(x, y, size, 8, 17) - 0.5;
  const fine = noise(x, y, size, 32, 19) - 0.5;
  if (kind === 'stucco') {
    const speck = hash(x, y, 7);
    // Subtle, non-directional limewash pores: the same noise drives pigment
    // and relief, without changing the existing albedo or facade geometry.
    const pitting = speck > 0.991 ? 1 : 0;
    return { shade: 1 + erosion * 0.16 + fine * 0.10 + grain * 0.09
      - pitting * 0.22, mortar: false,
    elevation: 0.5 + erosion * 0.20 + fine * 0.12 + grain * 0.10 - pitting * 0.15 };
  }
  if (kind === 'timber') {
    const board = Math.floor(x / 24);
    const edge = x % 24;
    const grainLine = Math.sin(x * 0.46 + noise(x, y, size, 8, 29) * 7) * 0.07;
    const knot = hash(Math.floor(x / 7), Math.floor(y / 11), 23) > 0.98 ? -0.18 : 0;
    return { shade: 0.96 + (hash(board, 0, 31) - 0.5) * 0.24
      + erosion * 0.10 + grainLine + grain * 0.07 + knot,
    mortar: edge < 2, elevation: 0.5 };
  }

  // Tile-friendly staggered courses. Slightly wandering grout and rounded
  // cobble corners break the grid, but keep UVs and old collision meshes.
  const { width, height } = spec;
  const row = Math.floor(y / height);
  const shifted = (x + (row % 2) * width / 2) % size;
  const column = Math.floor(shifted / width);
  const lx = shifted % width;
  const ly = y % height;
  const dx = Math.min(lx, width - 1 - lx);
  const dy = Math.min(ly, height - 1 - ly);
  const cobble = kind === 'cobble';
  const brick = kind === 'brick';
  const seamX = (cobble ? 1.9 : 1.25)
    + Math.sin(ly * 0.51 + row * 1.13 + column * 2.17) * (cobble ? 0.83 : brick ? 0.18 : 0.40);
  const seamY = (cobble ? 1.45 : brick ? 1.2 : 1.1)
    + Math.sin(lx * 0.36 + row * 1.71 + column * 0.42) * (cobble ? 0.57 : brick ? 0.15 : 0.3);
  const corner = cobble && dx < 4.5 && dy < 3.8
    && ((4.5 - dx) / 4.5) ** 2 + ((3.8 - dy) / 3.8) ** 2 > 0.92;
  const mortar = dx <= seamX || dy <= seamY || corner;
  const rounding = Math.min(1, Math.max(0,
    Math.min(dx - seamX, dy - seamY) / (cobble ? 4 : brick ? 2.5 : 5)));
  const stone = hash(column, row, cobble ? 41 : kind === 'roof' ? 43 : brick ? 67 : 47);
  const pit = hash(Math.floor(x / 3), Math.floor(y / 3), 61) > 0.988 ? -0.13 : 0;
  const shade = 0.98 + (stone - 0.5) * (cobble ? 0.37 : brick ? 0.24 : 0.30)
    + erosion * (brick ? 0.17 : 0.24) + fine * 0.13 + grain * 0.08 + pit
    + (rounding - 0.5) * (cobble ? 0.23 : brick ? 0.11 : 0.17);
  // Elevation feeds a tangent-space normal map: actual light direction makes
  // the mortar sink and the weathered stone rise, without extra triangles.
  const elevation = mortar ? 0.10
    : 0.45 + rounding * (cobble ? 0.37 : 0.28) + fine * 0.11;
  return { shade, mortar, elevation, stone };
}

const byte = value => Math.max(0, Math.min(255, Math.round(value)));
// Albedo and normal-map textures share the same immutable-by-convention
// generated bytes. Avoid running the expensive noise sampler twice per kind.
const surfaceCache = new Map();

export function chroniclesTownSurfacePixels(kind) {
  const spec = SURFACES[kind];
  if (!spec) throw new Error('Unsupported Swordhaven material: ' + kind);
  if (surfaceCache.has(kind)) return surfaceCache.get(kind);
  const { size, base } = spec;
  const pixels = new Uint8Array(size * size * 4);
  // One shared normal atlas per material: stone joints, roof shingles and
  // fine limewash pores all respond to light without extra polygons.
  const stoneRelief = kind === 'masonry' || kind === 'brick' || kind === 'cobble'
    || kind === 'roof' || kind === 'stucco';
  const heights = stoneRelief ? new Float32Array(size * size) : null;
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const detail = surfaceDetail(kind, x, y, spec);
      const moss = kind === 'cobble' && detail.mortar
        && noise(x, y, size, 16, 53) > 0.68;
      const lichen = kind === 'masonry' && !detail.mortar
        && hash(Math.floor(x / 3), Math.floor(y / 3), 59) > 0.993;
      const index = y * size + x;
      const offset = index * 4;
      if (heights) heights[index] = detail.elevation;
      for (let channel = 0; channel < 3; channel += 1) {
        const pigment = detail.mortar
          ? (moss ? [76, 98, 55] : kind === 'brick' ? [163, 150, 137] : [95, 89, 80])[channel]
          : lichen ? [130, 137, 100][channel]
          : base[channel] * detail.shade
            + (channel === 0 ? 1 : channel === 2 ? -1 : 0) * ((detail.stone ?? 0.5) - 0.5) * 13;
        pixels[offset + channel] = byte(pigment);
      }
      pixels[offset + 3] = 255;
    }
  }
  if (!heights) {
    const result = { size, pixels };
    surfaceCache.set(kind, result);
    return result;
  }

  // Periodic central differences preserve the repeating atlas at the edges.
  // Standard tangent-space RGB; linear-data texture, not sRGB albedo.
  const normals = new Uint8Array(pixels.length);
  const heightAt = (x, y) => heights[((y + size) % size) * size + ((x + size) % size)];
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const slopeX = (heightAt(x + 1, y) - heightAt(x - 1, y)) * 1.6;
      const slopeY = (heightAt(x, y + 1) - heightAt(x, y - 1)) * 1.6;
      const length = Math.hypot(slopeX, slopeY, 1);
      const offset = (y * size + x) * 4;
      normals[offset] = byte(127.5 * (1 - slopeX / length));
      normals[offset + 1] = byte(127.5 * (1 - slopeY / length));
      normals[offset + 2] = byte(127.5 * (1 + 1 / length));
      normals[offset + 3] = 255;
    }
  }
  const result = { size, pixels, normals };
  surfaceCache.set(kind, result);
  return result;
}
